import XCTest
@testable import SessionLauncherCore

final class ClaudeSessionReaderTests: XCTestCase {
    private let webapp = "/Users/me/work/acme/webapp"
    private let webappFolder = "projects/-Users-me-work-acme-webapp"

    func testReadsTitleProjectAndLastPrompt() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/aaaa-1111.jsonl", [
            ClaudeRecord.user("<command-name>/clear</command-name>", cwd: webapp),
            ClaudeRecord.user("Fix the login redirect", cwd: webapp),
            ClaudeRecord.toolResult(cwd: webapp),
            ClaudeRecord.aiTitle("Early title"),
            ClaudeRecord.aiTitle("Fix login redirect"),
            ClaudeRecord.lastPrompt("now run the migration tests"),
        ])

        let sessions = ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false }).read().sessions

        XCTAssertEqual(sessions.count, 1)
        let session = try XCTUnwrap(sessions.first)
        XCTAssertEqual(session.provider, .claude)
        XCTAssertEqual(session.sessionID, "aaaa-1111")
        XCTAssertEqual(session.title, "Fix login redirect")
        XCTAssertEqual(session.projectPath, webapp)
        XCTAssertEqual(session.projectName, "webapp")
        XCTAssertEqual(session.lastPrompt, "now run the migration tests")
        XCTAssertNil(session.activity)
    }

    func testTitleFallbackOrder() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/custom.jsonl", [
            ClaudeRecord.user("first prompt", cwd: webapp),
            ClaudeRecord.aiTitle("AI title"),
            ClaudeRecord.customTitle("My own name"),
        ])
        try fixture.writeLines("\(webappFolder)/prompt.jsonl", [
            ClaudeRecord.user("  \n  Please   refactor\tthe reader  \nsecond line", cwd: webapp),
        ])

        let titles = Dictionary(uniqueKeysWithValues: ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false })
            .read().sessions.map { ($0.sessionID, $0.title) })

        XCTAssertEqual(titles["custom"], "My own name")
        XCTAssertEqual(titles["prompt"], "Please refactor the reader")
    }

    func testFallbackTitleUsesProjectAndShortID() {
        XCTAssertEqual(TextExcerpt.fallbackTitle(projectPath: "/a/webapp", sessionID: "0123456789abcdef"), "webapp · 01234567")
        XCTAssertEqual(TextExcerpt.fallbackTitle(projectPath: "", sessionID: ""), "Untitled session")
    }

    func testFiltersNonInteractiveAndEmptySessions() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/sdk.jsonl", [
            ClaudeRecord.user("summarise this", cwd: webapp, entrypoint: "sdk-cli"),
        ])
        try fixture.writeLines("\(webappFolder)/meta-only.jsonl", [
            ClaudeRecord.user("Caveat: The messages below were generated by the user", cwd: webapp, isMeta: true),
            ClaudeRecord.toolResult(cwd: webapp),
        ])
        try fixture.writeLines("\(webappFolder)/parent/subagents/agent-1.jsonl", [
            ClaudeRecord.user("subagent task", cwd: webapp),
        ])
        try fixture.writeLines("\(webappFolder)/real.jsonl", [
            ClaudeRecord.user("real work", cwd: webapp),
        ])

        let ids = ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false }).read().sessions.map(\.sessionID)

        XCTAssertEqual(ids, ["real"])
    }

    func testPrefersCwdMatchingProjectFolder() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/moved.jsonl", [
            ClaudeRecord.user("start", cwd: "/Users/me/work/acme/webapp/server"),
            ClaudeRecord.user("continue", cwd: webapp),
        ])

        let session = try XCTUnwrap(ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false }).read().sessions.first)

        XCTAssertEqual(session.projectPath, webapp)
    }

    func testEncodedFolderName() {
        XCTAssertEqual(ClaudeSessionReader.encodedFolderName(for: "/Users/me/my app/v1.2"), "-Users-me-my-app-v1-2")
    }

    func testIncrementalScanPicksUpAppendedRecordsAndPartialLines() throws {
        let fixture = try FixtureDirectory()
        let path = "\(webappFolder)/grow.jsonl"
        try fixture.writeLines(path, [ClaudeRecord.user("first", cwd: webapp)])
        let reader = ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false })
        XCTAssertEqual(reader.read().sessions.first?.title, "first")

        // A half-written line must be ignored until it is complete.
        try fixture.append(path, #"{"type":"ai-title","aiTitle":"Grown ti"#)
        XCTAssertEqual(reader.read().sessions.first?.title, "first")

        try fixture.append(path, "tle\",\"sessionId\":\"s\"}\n")
        XCTAssertEqual(reader.read().sessions.first?.title, "Grown title")
    }

    func testSkipsOversizedAndMalformedLines() throws {
        let fixture = try FixtureDirectory()
        let huge = String(repeating: "x", count: 2 << 20)
        try fixture.writeLines("\(webappFolder)/big.jsonl", [
            ClaudeRecord.user("hello", cwd: webapp),
            "{not json",
            #"{"type":"user","blob":"\#(huge)"}"#,
            ClaudeRecord.aiTitle("Still readable"),
        ])

        let session = try XCTUnwrap(ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false }).read().sessions.first)

        XCTAssertEqual(session.title, "Still readable")
    }

    func testRunningRegistryMarksSessionActive() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/live.jsonl", [ClaudeRecord.user("hi", cwd: webapp)])
        try fixture.writeLines("\(webappFolder)/closed.jsonl", [ClaudeRecord.user("hi", cwd: webapp)])
        try fixture.writeLines("sessions/111.json", [["pid": 111, "sessionId": "live"]])
        try fixture.writeLines("sessions/222.json", [["pid": 222, "sessionId": "closed"]])

        let sessions = ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { $0 == 111 }).read().sessions
        let activity = Dictionary(uniqueKeysWithValues: sessions.map { ($0.sessionID, $0.activity) })

        XCTAssertEqual(activity["live"], .some(.running(pid: 111)))
        XCTAssertEqual(activity["closed"], .some(nil))
    }

    func testAcceptsSpacedJSONAndTypeKeyAfterLongFields() throws {
        let fixture = try FixtureDirectory()
        let padding = String(repeating: "p", count: 5_000)
        try fixture.writeLines("\(webappFolder)/spaced.jsonl", [
            #"{"padding": "\#(padding)", "type": "user", "cwd": "\#(webapp)", "entrypoint": "cli", "message": {"role": "user", "content": "spaced prompt"}}"#,
            #"{"sessionId": "s", "type": "ai-title", "aiTitle": "Spaced title"}"#,
        ])

        let session = try XCTUnwrap(ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in false }).read().sessions.first)

        XCTAssertEqual(session.title, "Spaced title")
        XCTAssertEqual(session.projectPath, webapp)
    }

    func testPartlyUnrecognisedTranscriptsAreReported() throws {
        let fixture = try FixtureDirectory()
        try fixture.writeLines("\(webappFolder)/old-format.jsonl", [ClaudeRecord.user("readable", cwd: webapp)])
        try fixture.writeLines("\(webappFolder)/new-format.jsonl", [["kind": "message", "body": "hi"]])
        try "".write(to: fixture.url("\(webappFolder)/empty.jsonl"), atomically: true, encoding: .utf8)
        // Opened and closed without a prompt: current format, nothing to resume, not a warning.
        try fixture.writeLines("\(webappFolder)/no-prompt.jsonl", [
            ["type": "last-prompt", "leafUuid": "x", "sessionId": "s"],
            ["type": "mode", "mode": "normal", "sessionId": "s"],
        ])

        guard case .partial(let sessions, let message) = ClaudeSessionReader(claudeHome: fixture.root).read() else {
            return XCTFail("A transcript in an unknown format should be reported")
        }
        XCTAssertEqual(sessions.map(\.sessionID), ["old-format"])
        XCTAssertTrue(message.contains("1 of 3"), message)
    }

    func testCurrentActivityRereadsRegistry() throws {
        let fixture = try FixtureDirectory()
        let reader = ClaudeSessionReader(claudeHome: fixture.root, isProcessAlive: { _ in true })
        XCTAssertNil(reader.currentActivity(sessionID: "late"))

        try fixture.writeLines("sessions/333.json", [["pid": 333, "sessionId": "late"]])

        XCTAssertEqual(reader.currentActivity(sessionID: "late"), .running(pid: 333))
    }

    func testUnavailableAndUnsupported() throws {
        let empty = try FixtureDirectory()
        guard case .unavailable = ClaudeSessionReader(claudeHome: empty.root).read() else {
            return XCTFail("Missing projects folder should be unavailable")
        }

        let changed = try FixtureDirectory()
        try changed.writeLines("\(webappFolder)/new-format.jsonl", [["kind": "message", "body": "hi"]])
        guard case .unsupported = ClaudeSessionReader(claudeHome: changed.root).read() else {
            return XCTFail("Unrecognised records should be unsupported")
        }
    }
}
